#!/usr/bin/env python3
"""src/phys/rc_addr.h: the arcade addresses the port's C code uses, for the build in $WMMT_MAIN.

The C code was written against the Japan 3DX+ `main`: it names game state as RCA(98028e4) and calls
recompiled functions as f_898317c. For another build this header maps each to that build's address
(tools/addrs/*.json, see wmmtaddr.py), as macros, so the C code stays the same for every build.

  python3 mkrcaddr.py <src dir> <out header>      (WMMT_MAIN=<main>)"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from wmmtaddr import A  # noqa: E402


def main():
    src, out = sys.argv[1:3]
    rca, funcs = set(), set()
    for root, _, files in os.walk(src):
        for f in files:
            if not f.endswith((".c", ".h")) or f in ("phys_rc.c", "rc_addr.h"):
                continue
            text = open(os.path.join(root, f), encoding="utf8", errors="replace").read()
            rca |= set(re.findall(r"\bRCA\(([0-9a-f]{7})\)", text))
            funcs |= set(re.findall(r"\bf_([0-9a-f]{7})\b", text))
    o = ["/* Generated by tools/recomp/mkrcaddr.py for the arcade `main` of this build: do not edit. */",
         "#ifndef RC_ADDR_H", "#define RC_ADDR_H", "",
         "/* game state: RCA(98028e4) is the address, in this build, of what the Japan build has there */"]
    for a in sorted(rca):
        o.append("#define RCA_%s 0x%xu" % (a, A(int(a, 16))))
    o += ["", "/* recompiled functions: the Japan build's names for this build's */"]
    for a in sorted(funcs):
        t = A(int(a, 16))
        if t != int(a, 16):
            o.append("#define f_%s f_%x" % (a, t))
    base, end = A(0x092f1b20), A(0x0993a468)
    mem_base, heap_base = base & ~0xffff, (end + 0xffff) & ~0xffff
    heap_size, stack_size = 0x400000, 0x100000
    o += ["", "/* the image (main's rodata..bss at the arcade's own addresses), then the heap and the stack",
          " * right after it, so that one range check finds any of them */",
          "#define RC_IMG_BASE 0x%xu" % base, "#define RC_IMG_END 0x%xu" % end,
          "#define RC_MEM_BASE 0x%xu" % mem_base, "#define RC_HEAP_BASE 0x%xu" % heap_base,
          "#define RC_HEAP_SIZE 0x%xu" % heap_size, "#define RC_STACK_SIZE 0x%xu" % stack_size,
          "#define RC_STACK_TOP 0x%xu" % (heap_base + heap_size + stack_size), "",
          "#define RCA(a) RCA_##a", "", "#endif", ""]
    open(out, "w").write("\n".join(o))
    print("%s: %d addresses, %d functions" % (out, len(rca), len(funcs)))


if __name__ == "__main__":
    main()
