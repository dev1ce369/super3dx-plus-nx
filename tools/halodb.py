"""Read where each car's headlight flares sit out of the arcade's car models, and write src/halodb.h.

usage: halodb.py <main> <data dir>   (WMMT_MAIN for tools/recomp/x86emu.py; the data dir is the arcade's data/)

- clCarLampManager's constructor (A(0x8601cf8)) makes one clCarLampHalo (A(0x8626990) update) at each of the
  body model's transforms named by the table at A(0x93d9cc0): HL_NULL_R1..R4, HL_NULL_L1..L4, in that order (a
  car has the ones its body has; R and L are the car's right and left, x negative and positive). Each halo
  draws data/effect/car_frontlight.igb's head02 and head03 quads at it (src/lights.c lights_draw_halos).
- nsCarLamp::CheckHaloExceptByCarType (A(0x85ffdd0)) is true for emCarID 0x25 and 0x5f: those two cars have no halos
  (the car of a pack is tools/brakelamps.json's "cars").

Output: HALO_N[CARDB_NPACKS][4] and HALO_POS[CARDB_NPACKS][4][8][3] by CARDB_PACKS and body (0 stock, 1..3 aero A..C):
the lamps' positions in the body model's space (the car's space, 1 unit = 10 cm).
"""
from wmmtaddr import A  # the arcade addresses of the build being read
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "stage"))
import numpy as np  # noqa: E402
import lualite  # noqa: E402
from igb import IGB  # noqa: E402
from scene import obj_list  # noqa: E402

EXCEPT = (0x25, 0x5f)  # CheckHaloExceptByCarType's two cars
NAMES = ["HL_NULL_R1", "HL_NULL_R2", "HL_NULL_R3", "HL_NULL_R4", "HL_NULL_L1", "HL_NULL_L2", "HL_NULL_L3", "HL_NULL_L4"]
BODIES = ("normal", "aero_a", "aero_b", "aero_c")


def lamps(path):
    """name -> position of the HL_NULL transforms in the body model"""
    f = IGB(path)
    info = f.of_type("igSceneInfo")
    found = {}

    def walk(node, mat):
        if node is None or node.mem is not None:
            return
        name = None
        if node.type in ("igGroup", "igTransform") and node[2] is not None:
            name = f.string(node[2])
        if node.type == "igTransform" and node[8] is not None:
            mat = np.frombuffer(node[8].raw, dtype="<f4").reshape(4, 4) @ mat
        if name in NAMES and name not in found:
            found[name] = [float(v) for v in mat[3, :3]]
        if node.type in ("igGroup", "igTransform"):
            for c in obj_list(f, f.ref(node[7])):
                walk(c, mat)

    walk(f.ref(info[0][5]), np.eye(4, dtype="f4"))
    return found


def main():
    data = sys.argv[2]
    root = os.path.dirname(os.path.abspath(data.rstrip("/")))
    cardb = open(os.path.join(HERE, "..", "src", "cardb.h")).read()
    packs = re.findall(r'"([^"]+)"', cardb[cardb.index("CARDB_PACKS["):cardb.index("};", cardb.index("CARDB_PACKS["))])
    # the story rivals' own cars (src/rivaldb.h RIVALDB_CHARA, data/characar/<folder>) are packs after the car select's
    chara = []
    rv = os.path.join(HERE, "..", "src", "rivaldb.h")
    if os.path.isfile(rv):
        txt = open(rv).read()
        a = txt.index("RIVALDB_CHARA[")
        chara = re.findall(r'"([^"]+)"', txt[a:txt.index("};", a)])
    cars = {k.lower(): v for k, v in json.load(open(os.path.join(HERE, "brakelamps.json")))["cars"].items()}
    cf = lambda v: ("%g" % round(v, 3)) + ("" if "." in ("%g" % round(v, 3)) or "e" in ("%g" % round(v, 3)) else ".0") + "f"
    out = ["/* Generated by tools/halodb.py from the arcade's car models: do not edit. */", "#ifndef HALODB_H", "#define HALODB_H", "",
           "/* by CARDB_PACKS and body (0 stock, 1..3 aero A..C): how many headlight flares the car has, and where (the body",
           " * model's HL_NULL_R1..R4, L1..L4 that exist, in the car's space); none for the two cars CheckHaloExceptByCarType names */"]
    n_rows, p_rows = [], []
    total = 0
    for k, folder in enumerate(packs + chara):
        car_id = cars.get(folder.lower(), -1)
        lua = os.path.join(data, "car" if k < len(packs) else "characar", folder, "car.lua")
        counts, poss = [], []
        for bi, body in enumerate(BODIES):
            pts = []
            if k >= len(packs) and bi:
                counts.append(0)
                poss.append("{ " + ", ".join(["{ 0.0f, 0.0f, 0.0f }"] * 8) + " }")
                continue
            if os.path.isfile(lua) and car_id not in EXCEPT:
                car = lualite.load(lua)
                rel = car["BodyIGB"].get(body)
                path = os.path.join(root, rel) if rel else None
                if path and os.path.isfile(path):
                    found = lamps(path)
                    pts = [found[n] for n in NAMES if n in found]
            counts.append(len(pts))
            total += len(pts)
            pts += [[0.0, 0.0, 0.0]] * (8 - len(pts))
            poss.append("{ " + ", ".join("{ %s, %s, %s }" % tuple(cf(v) for v in p) for p in pts) + " }")
        n_rows.append("  { %s }, /* %s */" % (", ".join(map(str, counts)), folder))
        p_rows.append("  { /* %s */\n    %s\n  }," % (folder, ",\n    ".join(poss)))
    out.append("static const unsigned char HALO_N[%d][4] = {" % (len(packs) + len(chara)))
    out += n_rows + ["};", "static const float HALO_POS[%d][4][8][3] = {" % (len(packs) + len(chara))] + p_rows + ["};", "", "#endif", ""]
    open(os.path.join(HERE, "..", "src", "halodb.h"), "w").write("\n".join(out))
    print("%d packs and %d story cars, %d flares -> src/halodb.h" % (len(packs), len(chara), total))


main()
